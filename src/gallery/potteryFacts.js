export const POTTERY_FACT_COUNT = POTTERY_FACTS.length;

/**
 * Random fact (e.g. tests). Prefer `pickCuratorialFactForShape` when saving a real pot.
 * @returns {{ fact: string, source: string, url: string }}
 */
export function pickCuratorialFact() {
  const i = Math.floor(Math.random() * POTTERY_FACTS.length);
  const { fact, source, url } = POTTERY_FACTS[i];
  return { fact, source, url };
}

function hashIdToFactIndex(idStr, len) {
  let h = 2166136261;
  for (let i = 0; i < idStr.length; i++) {
    h ^= idStr.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return len ? (h >>> 0) % len : 0;
}

/**
 * Pick fact index best matching shape hint tags; tie-break with tieKey string.
 * @param {{ tags?: string[], primary?: string }} hint
 * @param {string} tieKey
 */
function pickFactIndexForShapeHint(hint, tieKey) {
  const want = new Set(hint?.tags || []);
  if (hint?.primary) want.add(hint.primary);
  let bestScore = -1;
  const ties = [];
  for (let i = 0; i < POTTERY_FACTS.length; i++) {
    const tags = FACT_STYLE_TAGS[i] || [];
    let s = 0;
    for (const w of want) {
      if (tags.includes(w)) s += 3;
    }
    if (s > bestScore) {
      bestScore = s;
      ties.length = 0;
      ties.push(i);
    } else if (s === bestScore && s > 0) {
      ties.push(i);
    }
  }
  if (bestScore <= 0 || ties.length === 0) {
    return hashIdToFactIndex(String(tieKey ?? ''), POTTERY_FACTS.length);
  }
  return ties[hashIdToFactIndex(String(tieKey ?? ''), ties.length)];
}

/**
 * Curatorial fact to save: chosen by overlap between vessel shape hint and fact style tags.
 * @param {{ tags?: string[], primary?: string }} hint  from computePotShapeHint
 * @param {string} tieKey  e.g. `${name}_${Date.now()}` to spread ties across saves
 */
export function pickCuratorialFactForShape(hint, tieKey) {
  const i = pickFactIndexForShapeHint(hint, tieKey);
  const { fact, source, url } = POTTERY_FACTS[i];
  return { fact, source, url };
}

/**
 * Gallery display: saved fact wins; else match `pot_shape_hint`; else stable hash by row id.
 *
 * @param {object|null|undefined} stored  `clay_model_data.curatorial_fact`
 * @param {string} [rowId]  `entry.id`
 * @param {object|null|undefined} clay  `clay_model_data` (for `pot_shape_hint`)
 */
export function resolveCuratorialFactForGallery(stored, rowId, clay) {
  if (stored && typeof stored.fact === 'string' && stored.fact.trim()) {
    return {
      fact: stored.fact.trim(),
      source:
        typeof stored.source === 'string' && stored.source.trim()
          ? stored.source.trim()
          : 'Reference',
      url: typeof stored.url === 'string' ? stored.url.trim() : '',
    };
  }
  const hint = clay && clay.pot_shape_hint;
  if (hint && (hint.primary || (Array.isArray(hint.tags) && hint.tags.length > 0))) {
    const { fact, source, url } = pickCuratorialFactForShape(hint, String(rowId ?? ''));
    return { fact, source, url };
  }
  const i = hashIdToFactIndex(String(rowId ?? ''), POTTERY_FACTS.length);
  const { fact, source, url } = POTTERY_FACTS[i];
  return { fact, source, url };
}
